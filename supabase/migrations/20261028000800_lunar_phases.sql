-- Lunar phase events supplied for 2025–2026. Store orasolare verbatim because
-- the source's compact decimal-like format is ambiguous for some single-digit
-- minute values (for example, 7.6).
create table public.lunar_phases (
  phase_date date not null,
  phase_code text not null check (phase_code in ('LN', 'LP', 'PQ', 'UQ')),
  solar_time_source text not null,
  created_at timestamptz not null default now(),
  primary key (phase_date, phase_code)
);
comment on table public.lunar_phases is 'Supplied lunar phase calendar; solar_time_source preserves the orasolare string exactly as provided.';
comment on column public.lunar_phases.solar_time_source is 'Original orasolare value retained verbatim; no timezone or minute interpretation is applied.';
create index lunar_phases_date_idx on public.lunar_phases(phase_date);

